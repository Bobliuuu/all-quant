#!/usr/bin/env python3
"""Generate hip/backend_hip.cpp and hip/lattice_ext_kernels_hip.hpp from the CUDA test
backend (cuda/backend_cuda.cu, cuda/lattice_ext_kernels.cuh) by explicit renames, so the
HIP and CUDA backends drive their kernels identically."""
import os, re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
R = [
    (r'#include <cuda_runtime\.h>', '#include "hq_hip_compat.hpp"'),
    (r'#include <cuda_bf16\.h>\n', ''), (r'#include <cuda_fp8\.h>\n', ''),
    (r'#include <cublasLt\.h>', '#include <hipblaslt/hipblaslt.h>'),
    (r'"stage2_cuda_decoder\.h"', '"stage2_hip_decoder.h"'), (r'"stage2_cuda_encoder\.h"', '"stage2_hip_encoder.h"'),
    (r'"stage3_cuda_decoder\.h"', '"stage3_hip_decoder.h"'), (r'"rht_cuda\.cu"', '"rht_hip.hip"'),
    (r'"lattice_ext_kernels\.cuh"', '"lattice_ext_kernels_hip.hpp"'),
    (r'Stage2CudaEncoder', 'Stage2HipEncoder'), (r'Stage2CudaDecoder', 'Stage2HipDecoder'), (r'Stage3CudaDecoder', 'Stage3HipDecoder'),
    (r'cublasLt', 'hipblasLt'), (r'CUBLASLT_', 'HIPBLASLT_'), (r'CUBLAS_', 'HIPBLAS_'), (r'CUDA_R_', 'HIP_R_'),
    (r'cublasStatus_t', 'hipblasStatus_t'), (r'cublasOperation_t', 'hipblasOperation_t'),
    (r'\bcuda(Malloc|Free|Memset|Memcpy|MemcpyHostToDevice|MemcpyDeviceToHost|MemcpyDeviceToDevice|DeviceSynchronize|GetLastError|'
     r'GetErrorString|Error_t|Success|Stream_t|Event_t|EventCreate|EventRecord|EventSynchronize|EventElapsedTime|EventDestroy|'
     r'GetDeviceProperties)\b', r'hip\1'),
    (r'cudaDeviceProp', 'hipDeviceProp_t'),
    (r'__nv_bfloat16', 'hq_bf16_t'), (r'__bfloat162float', 'hq_bf162float'), (r'__float2bfloat16', 'hq_float2bf16'),
    (r'__nv_fp8_e4m3\(v\)\.__x', 'hqn::f2e4m3_rn(v)'),
    (r'"cuda:"', '"hip:"'), (r'" sm_" \+ std::to_string\(p\.major\) \+ std::to_string\(p\.minor\)', '" " + std::string(p.gcnArchName)'),
    (r'CUDA %s', 'HIP %s'), (r'\bcheck_cuda\b', 'check_hip'),
]


def conv(src, dst, extra=()):
    s = open(os.path.join(ROOT, src)).read()
    for a, b in list(R) + list(extra):
        s = re.sub(a, b, s)
    s = ("// GENERATED by tools/make_hip_backend.py from " + src + " -- do not edit by hand.\n") + s
    open(os.path.join(ROOT, dst), "w").write(s)
    left = [l for l in s.splitlines() if re.search(r'\bcuda|cublas|__nv_', l) and not l.strip().startswith("//")]
    print(dst, "leftover:", left)


# hipBLASLt may have no int8->int32 solution for a given shape/arch; fall back to a
# plain dot4 kernel so the int8 path still runs (reported in the bench output).
GEMM_FALLBACK = r'''
__global__ void int8_gemm_tn_fallback(const int8_t* __restrict__ A, const int8_t* __restrict__ B, int32_t* __restrict__ C,
                                      int M, int N, int K) {
  const int m = blockIdx.y * 16 + threadIdx.y, n = blockIdx.x * 16 + threadIdx.x;
  if (m >= M || n >= N) return;
  const int* a = reinterpret_cast<const int*>(A + (long)m * K);
  const int* b = reinterpret_cast<const int*>(B + (long)n * K);
  int acc = 0;
  for (int k = 0; k < K / 4; ++k) acc = __builtin_amdgcn_sdot4(a[k], b[k], acc, false);
  C[(long)n * M + m] = acc;
}
inline int& gemm_fallback_used() { static int v = 0; return v; }
'''


def main():
    conv("cuda/lattice_ext_kernels.cuh", "hip/lattice_ext_kernels_hip.hpp", extra=[
        (r'namespace lxk \{\nconstexpr int kThreadsPerBlock = 256;', 'namespace lxk {\nconstexpr int kThreadsPerBlock = 256;' + GEMM_FALLBACK.replace('\\', '\\\\')),
        (r'  if \(nh <= 0\) \{ fprintf\(stderr, "no int8 GEMM algo M=%d N=%d K=%d\\n", M, N, K\); exit\(1\); \}',
         '  if (nh <= 0) {\n    gemm_fallback_used() = 1;\n    dim3 g((N + 15) / 16, (M + 15) / 16), b(16, 16);\n'
         '    int8_gemm_tn_fallback<<<g, b>>>(A, B, C, M, N, K);\n    hipblasLtMatmulPreferenceDestroy(pref); hipblasLtMatrixLayoutDestroy(la);\n'
         '    hipblasLtMatrixLayoutDestroy(lb); hipblasLtMatrixLayoutDestroy(lc); hipblasLtMatmulDescDestroy(desc);\n    return;\n  }'),
        (r'cublasLtMatmulHeuristicResult_t heur\{\};', 'hipblasLtMatmulHeuristicResult_t heur{};'),
        (r'hipblasLtMatmulAlgoGetHeuristic\(lt, desc, la, lb, lc, lc, pref, 1, &heur, &nh\)\);',
         'hipblasLtMatmulAlgoGetHeuristic(lt, desc, la, lb, lc, lc, pref, 1, &heur, &nh) == HIPBLAS_STATUS_SUCCESS ? HIPBLAS_STATUS_SUCCESS : (nh = 0, HIPBLAS_STATUS_SUCCESS));'),
    ])
    conv("cuda/backend_cuda.cu", "hip/backend_hip.cpp", extra=[
        (r'// backend_cuda\.cu -- CUDA reference backend.*?\n#include', '// backend_hip.cpp -- HIP port backend (hip/*), same driver logic as cuda/backend_cuda.cu.\n#include', ),
        (r'std::string g_name;', 'std::string g_name;'),
    ])


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Collect the ports' generated results into results/derived/ports_data.json for README.spec.yml (README + video).

Sources (each generated by the port's own script, never typed by hand):
  ports/hyperquant/results/derived/tables.json   (ports/hyperquant/tools/make_tables.py)
  ports/pearlquant/results/SUMMARY.md            (ports/pearlquant/tools/summarize.py)
Paper / blog values are the ones those files already quote, except HQ_PAPER_BF16 (HyperQuant Sec. 6 Setup, also quoted in tables.md).
"""
import json, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parents[1]
HQ = ROOT / "ports/hyperquant/results/derived/tables.json"
PQ = ROOT / "ports/pearlquant/results/SUMMARY.md"
OUT = ROOT / "results/derived/ports_data.json"
HQ_PAPER_BF16 = 7.1606


def md_table(text, header_prefix):
    rows, on = [], False
    for l in text.splitlines():
        if l.startswith(header_prefix):
            on = True
            continue
        if on:
            if l.startswith("|---"):
                continue
            if not l.startswith("|"):
                break
            rows.append([c.strip() for c in l.strip().strip("|").split("|")])
    if not rows:
        raise SystemExit(f"table '{header_prefix}' not found in {PQ}")
    return rows


def lead_float(s):
    return float(re.match(r"-?[\d.]+", s).group(0))


def hyperquant():
    d = json.load(open(HQ, encoding="utf-8"))
    bf16 = d["bf16"]
    repro = [{"config": "bf16 baseline", "paper": HQ_PAPER_BF16, "ours": bf16}]
    for w in d["weights"]:
        if w["lattice"] == "e8int":
            repro.append({"config": f"E8 weights, {w['bps']} bps", "paper": w["paper"], "ours": w["tile1024"]})
    for h in d["higgs"]:
        if h["bps"] == 4:
            repro.append({"config": "HIGGS p=2 weights, 4 bps", "paper": h["paper"], "ours": h["ours"]})
    kv = {r["variant"]: r for r in d["kv"]}
    for v in ("signs", "qjl"):
        repro.append({"config": f"E8 KV cache, 2 bps ({v})", "paper": kv[v]["paper2"], "ours": kv[v]["ours2"]})
    for r in d["t7"]:
        if r["cast"] == "int8" and r["path"] == "wkv":
            repro.append({"config": "Table 7: int8 MMA, weights + KV, 4 bps", "paper": r["paper"], "ours": r["ours1024"]})
    for r in repro:
        r["delta"] = r["ours"] - r["paper"]

    tests = d["kernel_tests"]
    backends = sorted({t["backend"].split(" sg")[0] for t in tests})
    passed = {t["passed"] for t in tests}
    total = {t["passed"] + t["failed"] for t in tests}
    assert len(passed) == 1 and len(total) == 1, "backends disagree on the check count"

    H, M, MS, HS, A = ("H100 CUDA (upstream)", "MI300X HIP (port)", "MI300X SYCL (port, AdaptiveCpp HIP)",
                       "H100 SYCL (port, DPC++ CUDA)", "Arc B390 SYCL (port)")
    kb = {(r["bench"], r["case"]): r for r in d["kernel_bench"] if r["metric"] not in ("bitstream_GBps", "gbps_rw")}  # time metrics only
    # (bench, case, label, scale to ms); labels short enough for one table row in the video
    pick = [("decode", "fused bf16", "Decode, bf16", 1), ("decode", "fused int8", "Decode, int8", 1),
            ("gemv_layer", "", "GEMV", 1), ("gemm_ws", "q/o_proj 8", "GEMM", 1),
            ("attn", "8 511", "Attention", 1e-3)]
    kernels = []
    for b, c, lab, s in pick:
        r = kb[(b, c)]
        kernels.append({"bench": lab, "h100_cuda": r[H] * s, "mi300x_hip": r[M] * s, "mi300x_sycl": r[MS] * s, "h100_sycl": r[HS] * s,
                        "arc_b390_sycl": r[A] * s, "mi300x_over_h100": r[M] / r[H]})
    decode_ratios = [kb[("decode", c)][M] / kb[("decode", c)][H] for c in
                     ("2-kernel bf16", "fused bf16", "fused coop bf16", "fused fp8", "fused int8", "launcher bf16", "symbols(z)")]
    e2e = next(r for r in d["rocm_e2e"] if r["config"].startswith("w_real"))
    t10 = {r["config"]: r for r in d["t10"]}
    kv3 = min((r for r in d["kv"]), key=lambda r: r["ours3"])
    return {
        "bf16_ours": bf16, "bf16_paper": HQ_PAPER_BF16,
        "e8_w4_ours": next(r["ours"] for r in repro if r["config"] == "E8 weights, 4 bps"),
        "e8_w4_paper": next(r["paper"] for r in repro if r["config"] == "E8 weights, 4 bps"),
        "max_abs_delta_e8": max(abs(r["delta"]) for r in repro if r["config"].startswith("E8")),
        "kv3_delta": kv3["ours3"] - bf16,
        "repro": repro,
        "checks_passed": passed.pop(), "checks_total": total.pop(), "backends": len(backends),
        "e2e_mi300x": e2e["mi300x"], "e2e_h100": e2e["h100"],
        "t10_bf16_decode": t10["bf16"]["ours"]["decode_tok_s"], "t10_w_decode": t10["w"]["ours"]["decode_tok_s"],
        "decode_ratio_min": min(decode_ratios), "decode_ratio_max": max(decode_ratios),
        "kernels": kernels,
    }


def pearlquant():
    s = open(PQ, encoding="utf-8").read()
    rd = {r[0]: r for r in md_table(s, "| point |")}
    rd_rows = [{"point": "E8 codec, 2.75 bpv", "pearl": lead_float(rd["PQ 2.75 bpv"][1]), "ours_no_side": lead_float(rd["PQ 2.75 bpv"][2]),
                "ours_with_scale": lead_float(rd["PQ 2.75 bpv"][4])},
               {"point": "E8 codec, 3.75 bpv", "pearl": lead_float(rd["PQ 3.75 bpv"][1]), "ours_no_side": lead_float(rd["PQ 3.75 bpv"][2]),
                "ours_with_scale": lead_float(rd["PQ 3.75 bpv"][4])}]
    for k, lab in (("TurboQuant-MSE 3 b", "TurboQuant-MSE, 3 b"), ("NVFP4 4.5 bpv", "NVFP4, 4.5 bpv"), ("FP8 e4m3 8 bpv", "FP8 e4m3, 8 bpv")):
        rd_rows.append({"point": lab, "pearl": lead_float(rd[k][1]), "ours_no_side": lead_float(rd[k][2]), "ours_with_scale": None})

    kl = {r[0]: r for r in md_table(s, "| config |")}
    names = {"bf16": "bf16", "fp8-noscale": "FP8, no scale", "nvfp4": "NVFP4", "int4-g32": "int4, group 32",
             "tq-mse-3-kc": "TurboQuant-MSE 3 b (K centered)", "pq-3.2-kc": "E8 (ours), 3.2 bpv", "pq-2.3-kc": "E8 (ours), 2.3 bpv",
             "pq-2.1-kc": "E8 (ours), 2.1 bpv", "vor-3.2-kc": "E8 Voronoi ablation, 3.2 bpv"}
    kl_rows = [{"config": lab, "bpv": float(kl[k][1]), "kl": float(kl[k][2]), "ppl": float(kl[k][4]),
                "pearl_kl": float(kl[k][5]) if kl[k][5] else None} for k, lab in names.items()]
    ratios = [r["kl"] / r["pearl_kl"] for r in kl_rows if r["pearl_kl"]]

    niah = md_table(s, "| config | single needle")
    checks = md_table(s, "| backend | device | passed")
    tim = md_table(s, "| device | B | T |")
    kern = []
    for r in tim:
        if r[1:6] == ["8", "32768", "32", "8", "25/24"]:
            dev = re.sub(r"Intel\(R\) |\(TM\)|NVIDIA |AMD Instinct | 80GB HBM3| VF", "", r[0]).replace("  ", " ")
            kern.append({"device": dev, "pq_us": float(r[6]), "bf16_us": float(r[7]), "fp8_us": float(r[8]),
                         "vendor_bf16_us": lead_float(r[9]) if r[9] else None, "pq_over_bf16": float(r[6]) / float(r[7])})
    return {
        "rd": rd_rows, "kl": kl_rows,
        "rd_pearl_275": rd_rows[0]["pearl"], "rd_ours_275": rd_rows[0]["ours_with_scale"], "rd_ours_275_noside": rd_rows[0]["ours_no_side"],
        "kl_ours_32": float(kl["pq-3.2-kc"][2]), "kl_pearl_32": float(kl["pq-3.2-kc"][5]), "kl_nvfp4": float(kl["nvfp4"][2]),
        "kl_ratio_min": min(ratios), "kl_ratio_max": max(ratios),
        "niah_all_pass": all(c == "1.00" for r in niah for c in r[1:]), "niah_formats": len(niah),
        "checks_passed": int(checks[0][2].split("/")[0]), "checks_total": int(checks[0][2].split("/")[1]), "targets": len(checks),
        "worst_rel_l2": checks[0][3],
        "kernels": kern,
        "pq_over_bf16_min": min(k["pq_over_bf16"] for k in kern), "pq_over_bf16_max": max(k["pq_over_bf16"] for k in kern),
        **dict(zip(("bytes_pq", "bytes_bf16", "bytes_fp8"), map(int, re.search(r"\((\d+) B at 25/24\), bf16 (\d+) B, fp8 (\d+) B", s).groups()))),
    }


if __name__ == "__main__":
    out = {"_note": "generated by tools/ports_data.py from the ports' generated results; do not edit", "hyperquant": hyperquant(), "pearlquant": pearlquant()}
    OUT.write_text(json.dumps(out, indent=1) + "\n", encoding="utf-8")
    print("wrote", OUT.relative_to(ROOT))

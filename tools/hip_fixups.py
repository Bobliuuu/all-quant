#!/usr/bin/env python3
"""Step 2 of the HIP port: copy hip/gen/* (mechanical hipify output) to hip/ and apply
the hand fixes.  Every fix is listed here with its reason, and each must apply exactly
once, so the full CUDA->HIP delta = tools/hipify_hq.sh + this file."""
import os, re, shutil, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
GEN, HIP = os.path.join(ROOT, "hip", "gen"), os.path.join(ROOT, "hip")

FIXES = {
    # MI300X's native fp8 is E4M3-FNUZ (bias 8, no -0), not the OCP E4M3 (e4m3fn) that
    # __nv_fp8_e4m3 produces.  The stored byte must match CUDA, so convert in software
    # (hqn::f2e4m3_rn = RN + satfinite, bit-identical to __nv_fp8_e4m3(float)).
    "stage2_hip_decoder.hip": [
        ("      const __nv_fp8_e4m3 v(x_hat);\n      static_cast<uint8_t*>(out8)[i] = v.__x;",
         "      static_cast<uint8_t*>(out8)[i] = hqn::f2e4m3_rn(x_hat);"),
    ],
}


def main():
    for fn in sorted(os.listdir(GEN)):
        src = open(os.path.join(GEN, fn)).read()
        for old, new in FIXES.get(fn, []):
            n = src.count(old)
            if n != 1:
                sys.exit(f"{fn}: fix applies {n} times: {old[:60]!r}")
            src = src.replace(old, new)
        hdr = ("// HIP port of upstream HyperQuant (commit 227f3f6), generated by tools/hipify_hq.sh\n"
               "// + tools/hip_fixups.py from the file of the same role in ../upstream. MIT.\n")
        open(os.path.join(HIP, fn), "w").write(hdr + src)
    print("ok")


if __name__ == "__main__":
    main()
